"""Recheck public artifacts from disk without trusting the trainer's metrics.

This checks signatures, hashes, source offsets and partition integrity. It does
not replay optimization; see replay_finetune.py for that separate check.
"""
import argparse
from datetime import datetime,timezone
import hashlib
import json
from pathlib import Path
import sys
import numpy as np
from tokenizers import Tokenizer
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'src'))
from dawl_node.common import read_json, verify_signature, sha256, write_json, canonical_json
from dawl_finetune.data import file_hash, load


def verify(root, public):
    rows=[json.loads(l) for l in (root/'lineage.jsonl').read_text().splitlines() if l]
    previous=None;checked=0;serving=None
    for i,row in enumerate(rows):
        body=verify_signature(row,public)
        if body['sequence']!=i or body['previous']!=previous:raise ValueError('Broken lineage chain')
        previous=row['id']
        if body['kind']=='checkpoint':
            desc=body['payload'];folder=root/'checkpoints'/desc['name']
            for name,meta in desc['files'].items():
                if Path(name).name!=name:raise ValueError('Unsafe artifact name')
                path=folder/name
                if file_hash(path)!=meta['sha256'] or path.stat().st_size!=meta['bytes']:raise ValueError('Checkpoint hash mismatch')
                checked+=1
        if body['kind']=='experiment-inputs':
            for name,field in [('dataset-lock.json','dataset_lock_sha256'),('recipe.json','recipe_sha256'),('probes-lock.json','probes_sha256')]:
                if file_hash(root/name)!=body['payload'][field]:raise ValueError('Signed input changed')
        fields={'baseline':[('baseline.json','sha256')],
                'training-result':[('training-summary.json','summary_sha256'),('selected-evaluation.json','selected_evaluation_sha256')],
                'control-result':[('control-result.json','sha256')]}.get(body['kind'],[])
        for filename,field in fields:
            if file_hash(root/filename)!=body['payload'][field]:raise ValueError('Signed result changed')
        if body['kind']=='merged-export':
            desc=body['payload']
            for name,meta in desc['files'].items():
                if Path(name).name!=name:raise ValueError('Unsafe export filename')
                path=root/'exports'/desc['checkpoint']/name
                if file_hash(path)!=meta['sha256'] or path.stat().st_size!=meta['bytes']:raise ValueError('Export hash mismatch')
                checked+=1
        if body['kind']=='serving-package':
            if file_hash(root/'serving-package.json')!=body['payload']['sha256']:raise ValueError('Serving package changed')
            serving=read_json(root/'serving-package.json')
            for name,meta in serving['files'].items():
                path=(root/name).resolve()
                if not path.is_relative_to(root.resolve()):raise ValueError('Unsafe serving artifact path')
                if file_hash(path)!=meta['sha256'] or path.stat().st_size!=meta['bytes']:raise ValueError('Serving artifact changed: '+name)
                checked+=1
            cases={c['id']:c for c in read_json(root/'serving-evidence/finance-trust-cases-v1.json')['cases']}
            models={m['id']:m for m in serving['local_models']}
            for model in models.values():
                conversion=root/('conversion-inputs-'+model['checkpoint']+'.json')
                if not conversion.exists():continue
                for name,meta in read_json(conversion)['files'].items():
                    if Path(name).name!=name:raise ValueError('Unsafe conversion name')
                    expected_source=('exports/'+model['checkpoint']+'/' if name=='model.safetensors' else 'base/')+name
                    if meta['source']!=expected_source:raise ValueError('Unexpected conversion source')
                    if file_hash(root/meta['source'])!=meta['sha256']:raise ValueError('Conversion source changed')
            for name in serving['files']:
                if not name.startswith('serving-evidence/') or '--' not in Path(name).name:continue
                response=read_json(root/name)
                if sha256(response['answer'].encode())!=response['answer_sha256']:raise ValueError('Answer hash mismatch')
                if sha256(response['prompt'].encode())!=response['prompt_sha256']:raise ValueError('Prompt hash mismatch')
                if sha256(canonical_json(cases[response['case_id']]))!=response['case_sha256']:raise ValueError('Case hash mismatch')
                if response['model_id'] in models and response['metadata']['ollama_digest']!=models[response['model_id']]['digest']:
                    raise ValueError('Answer was generated by a different served model')
    books=read_json(root/'source-lock.json')['books'];raw={}
    for b in books:
        value=(root/b['file']).read_bytes()
        if sha256(value)!=b['sha256'] or len(value)!=b['bytes']:raise ValueError('Original source mismatch')
        raw[b['id']]=value
    for name,meta in read_json(root/'base-lock.json')['files'].items():
        if file_hash(root/'base'/name)!=meta['sha256']:raise ValueError('Base file mismatch')
        checked+=1
    segments=[json.loads(l) for l in (root/'segments.jsonl').read_text().splitlines()]
    for bid in raw:
        parts=sorted([r for r in segments if r['book_id']==bid],key=lambda r:r['start_byte'])
        for index,part in enumerate(parts):
            a,b=part['start_byte'],part['end_byte']
            if not 0<=a<b<=len(raw[bid]):raise ValueError('Invalid source offsets')
            if sha256(raw[bid][a:b])!=part['segment_sha256']:raise ValueError('Segment hash mismatch')
            if index and a<parts[index-1]['end_byte']:raise ValueError('Overlapping source segments')
    arrays=load(root);seen={};windows=0
    for split,array in arrays.items():
        for window in array:
            h=sha256(window.astype('<u4').tobytes())
            if h in seen:raise ValueError('Duplicate token window within/across partitions')
            seen[h]=split;windows+=1
    # Independently retokenize preserved source slices with the frozen tokenizer,
    # and compare the actual IDs with every stored training and holdout window.
    tokenizer=Tokenizer.from_file(str(root/'base/tokenizer.json'))
    positions={name:0 for name in arrays};dedup=set();replayed=0
    for part in segments:
        text=raw[part['book_id']][part['start_byte']:part['end_byte']].decode('utf-8')
        ids=tokenizer.encode(text,add_special_tokens=False).ids[128:-128]
        name=part['split']+'_'+part['domain'];count=0
        for offset in range(0,len(ids)-512,513):
            value=np.asarray(ids[offset:offset+513],dtype='<u4');h=sha256(value.tobytes())
            if h in dedup:continue
            dedup.add(h);position=positions[name]
            if position>=len(arrays[name]) or not np.array_equal(value,arrays[name][position]):raise ValueError('Source-to-token replay mismatch')
            positions[name]+=1;replayed+=1;count+=1
        if count!=part['windows']:raise ValueError('Segment window count mismatch')
    if any(positions[name]!=len(array) for name,array in arrays.items()):raise ValueError('Unexplained dataset windows')
    return {'schema':'hypertrix.local-artifact-verification/1','passed':True,'verified_utc':datetime.now(timezone.utc).isoformat(),
            'trusted_operator_public_key':public,'lineage_head':previous,'signed_records':len(rows),'source_books':len(books),
            'source_segments':len(segments),'unique_token_windows':windows,'retokenized_matching_windows':replayed,'checkpoint_and_base_files':checked,
            'serving_package_verified':serving is not None,
            'scope':'Separate CPU process rechecked signatures, hash-chain order, original sources, base files, non-overlapping byte segments, dataset hashes, unique token windows and checkpoint files, and independently retokenized every source segment to reproduce every stored token window. Optimization replay is reported separately.',
            'not_verified':['Upstream pretraining data lineage','Financial correctness','Causal attribution of an answer to a source','Independent organizational trust or Oracle quorum'],
            'verifier_script_sha256':file_hash(Path(__file__))}


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--root',type=Path,required=True);p.add_argument('--trusted-public',required=True);p.add_argument('--output',type=Path)
    a=p.parse_args();result=verify(a.root,a.trusted_public)
    if a.output:write_json(a.output,result)
    print(json.dumps(result,indent=2))
